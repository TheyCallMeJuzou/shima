// Shima Material 3 colour scheme from one seed colour, via Google's material-color-utilities.
//
// Writes:  shared/src/main/res/values/theme_colors.xml        (light, md_theme_<role>)
//          shared/src/main/res/values-night/theme_colors.xml  (dark)
//          mobile/src/main/java/com/oasisfeng/island/ui/ShimaColorSchemes.kt (Compose light/dark ColorScheme)
//
// Usage:   npm install --prefix <dir> @material/material-color-utilities@0.3.0
//          node art/theme/gen_theme.mjs <dir>/node_modules/@material/material-color-utilities/index.js [repo root]
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { pathToFileURL } from "node:url";

const SEED = "#C94F7C";     // Rose of the launcher icon's sea
const [mcuPath, root = "."] = process.argv.slice(2);
const { Hct, SchemeContent, MaterialDynamicColors: C, argbFromHex, hexFromArgb } = await import(pathToFileURL(mcuPath).href);

// SchemeContent keeps the seed's chroma, so the primary stays recognisably "Shima rose" (TonalSpot would mute it).
const scheme = dark => new SchemeContent(Hct.fromInt(argbFromHex(SEED)), dark, 0.0);
const ROLES = ["primary", "onPrimary", "primaryContainer", "onPrimaryContainer", "inversePrimary",
	"primaryFixed", "primaryFixedDim", "onPrimaryFixed", "onPrimaryFixedVariant",
	"secondary", "onSecondary", "secondaryContainer", "onSecondaryContainer",
	"secondaryFixed", "secondaryFixedDim", "onSecondaryFixed", "onSecondaryFixedVariant",
	"tertiary", "onTertiary", "tertiaryContainer", "onTertiaryContainer",
	"tertiaryFixed", "tertiaryFixedDim", "onTertiaryFixed", "onTertiaryFixedVariant",
	"error", "onError", "errorContainer", "onErrorContainer",
	"background", "onBackground", "surface", "onSurface", "surfaceVariant", "onSurfaceVariant",
	"surfaceDim", "surfaceBright", "surfaceContainerLowest", "surfaceContainerLow", "surfaceContainer",
	"surfaceContainerHigh", "surfaceContainerHighest", "inverseSurface", "inverseOnSurface", "surfaceTint",
	"outline", "outlineVariant", "shadow", "scrim"];
const colors = dark => { const s = scheme(dark); return ROLES.map(r => [r, hexFromArgb(C[r].getArgb(s)).toUpperCase()]); };
const snake = r => r.replace(/[A-Z]/g, c => "_" + c.toLowerCase());
const header = `Generated by art/theme/gen_theme.mjs from seed ${SEED} (Material 3, SchemeContent). Do not edit by hand.`;

for (const [dir, dark] of [["values", false], ["values-night", true]])
	writeFileSync(join(root, "shared/src/main/res", dir, "theme_colors.xml"),
		`<?xml version="1.0" encoding="utf-8"?>\n<!-- ${header} -->\n<resources>\n` +
		colors(dark).map(([r, hex]) => `    <color name="md_theme_${snake(r)}">${hex}</color>`).join("\n") + "\n</resources>\n");

// Compose Material3 1.1.x ColorScheme has no fixed/container-level surface roles; pass the ones it knows.
const COMPOSE_ROLES = new Set(["primary", "onPrimary", "primaryContainer", "onPrimaryContainer", "inversePrimary",
	"secondary", "onSecondary", "secondaryContainer", "onSecondaryContainer", "tertiary", "onTertiary", "tertiaryContainer",
	"onTertiaryContainer", "background", "onBackground", "surface", "onSurface", "surfaceVariant", "onSurfaceVariant",
	"surfaceTint", "inverseSurface", "inverseOnSurface", "error", "onError", "errorContainer", "onErrorContainer",
	"outline", "outlineVariant", "scrim"]);
const compose = (fn, dark) => `${fn}(\n` + colors(dark).filter(([r]) => COMPOSE_ROLES.has(r))
	.map(([r, hex]) => `\t${r} = Color(0xFF${hex.slice(1)}),`).join("\n") + "\n)";
writeFileSync(join(root, "mobile/src/main/java/com/oasisfeng/island/ui/ShimaColorSchemes.kt"),
	`// ${header}\npackage com.oasisfeng.island.ui\n\nimport androidx.compose.material3.darkColorScheme\n` +
	`import androidx.compose.material3.lightColorScheme\nimport androidx.compose.ui.graphics.Color\n\n` +
	`val ShimaLightColorScheme = ${compose("lightColorScheme", false)}\n\nval ShimaDarkColorScheme = ${compose("darkColorScheme", true)}\n`);

console.log("light primary", colors(false)[0][1], "dark primary", colors(true)[0][1]);
